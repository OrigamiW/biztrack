function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(function (element) {
        const key = element.getAttribute("data-i18n");
        element.innerHTML = i18next.t(key);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (element) {
        const key = element.getAttribute("data-i18n-placeholder");
        element.setAttribute("placeholder", i18next.t(key));
    });

    document.querySelectorAll("[data-i18n-title]").forEach(function (element) {
        const key = element.getAttribute("data-i18n-title");
        element.setAttribute("title", i18next.t(key));
    });

    document.querySelectorAll("[data-i18n-label]").forEach(function (element) {
        const key = element.getAttribute("data-i18n-label");
        element.setAttribute("label", i18next.t(key));
    });

    const languageButton = document.getElementById("language-toggle");
    if (languageButton) {
        languageButton.textContent = i18next.t("switchLanguage");
    }
}

function toggleLanguage() {
    const nextLanguage = i18next.language === "en" ? "zh" : "en";

    i18next.changeLanguage(nextLanguage, function () {
        localStorage.setItem("bizTrackLanguage", nextLanguage);
        applyTranslations();
    });
}

document.addEventListener("DOMContentLoaded", function () {
    const savedLanguage = localStorage.getItem("bizTrackLanguage") || "en";

    i18next.init(
        {
            lng: savedLanguage,
            fallbackLng: "en",
            resources: resources
        },
        function () {
            applyTranslations();
            document.dispatchEvent(new Event("i18nReady"));
        }
    );
});

window.applyTranslations = applyTranslations;
window.toggleLanguage = toggleLanguage;